// Receipt for a paid sponsor invoice. Rebuilt on demand from the stored invoice (nothing is saved). Plain Latin text only.
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import type { SponsorRow } from './sponsors';

const INK = rgb(0.145, 0.188, 0.122);
const MUTE = rgb(0.478, 0.518, 0.447);
const GREEN = rgb(0.31, 0.42, 0.227);
const SOFT = rgb(0.914, 0.929, 0.875);
const ascii = (s: string) => s.replace(/[−–—]/g, '-').replace(/·/g, '|').replace(/[^\x20-\x7e]/g, '');

export async function buildSponsorReceiptPdf(orgName: string, s: SponsorRow): Promise<Uint8Array> {
  const inv = s.invoice!;
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]);
  const reg = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const mono = await pdf.embedFont(StandardFonts.CourierBold);
  const money = ascii(new Intl.NumberFormat('en-CA', { style: 'currency', currency: s.currency }).format(inv.amountCents / 100));
  const date = (iso: string | null) => (iso ? new Date(iso).toLocaleDateString('en-CA', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' }) : '-');
  const M = 48;
  const text = (t: string, x: number, y: number, size: number, font = reg, color = INK) => page.drawText(ascii(t), { x, y, size, font, color });

  text('giveback', M, 740, 20, bold, GREEN);
  text('SPONSORSHIP RECEIPT', M, 712, 9, mono, MUTE);
  text(`Receipt for ${inv.invoiceNumber ?? 'invoice'}`, M, 684, 16, bold);
  text(`Thank you, ${s.name}. Your pledge to ${orgName} has been paid.`, M, 660, 11);

  page.drawRectangle({ x: M, y: 580, width: 516, height: 56, color: SOFT });
  text('Amount paid', M + 14, 602, 12, bold);
  text(money, 612 - M - 14 - bold.widthOfTextAtSize(money, 20), 600, 20, bold, GREEN);

  const kv: [string, string][] = [
    ['Paid to', `${orgName} (processed by giveback)`],
    ['Sponsor', s.name],
    ['Invoice', inv.invoiceNumber ?? '-'],
    ['Invoice sent', date(inv.sentAt)],
    ['Paid on', date(inv.paidAt)],
    ['Method', 'PayPal Invoicing'],
  ];
  let y = 540;
  for (const [k, v] of kv) {
    text(k, M, y, 10, reg, MUTE);
    text(v, M + 120, y, 10);
    y -= 20;
  }
  text('Sandbox demo: paid with PayPal sandbox money.', M, 49, 7.5, reg, MUTE);
  text('Generated by giveback', M, 36, 7.5, reg, MUTE);
  return pdf.save();
}
